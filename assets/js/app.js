const originals = new WeakMap();

function addLanguageToggle() {
  if (document.getElementById("languageToggle")) return;
  const button = document.createElement("button");
  button.id = "languageToggle";
  button.className = "lang-toggle";
  button.type = "button";
  button.setAttribute("aria-label", "Switch language");
  button.textContent = localStorage.getItem("nemesis-language") === "en" ? "RU" : "EN";

  const actions = document.querySelector(".nav-actions");
  if (actions) actions.prepend(button);
  else document.body.appendChild(button);

  button.addEventListener("click", () => {
    const next = getLanguage() === "ru" ? "en" : "ru";
    setLanguage(next);
  });
}

function getLanguage() {
  return localStorage.getItem("nemesis-language") || "ru";
}

function translateElement(el, language) {
  if (!originals.has(el)) originals.set(el, el.innerHTML);
  const original = originals.get(el);
  if (language === "en") {
    if (el.innerHTML !== original) el.innerHTML = original;
  } else if (translations[original] && el.innerHTML !== translations[original]) {
    el.innerHTML = translations[original];
  }
}

function translatePage(language) {
  document.documentElement.lang = language;
  document.querySelectorAll("body *").forEach(el => {
    if (el.children.length === 0 || translations[el.innerHTML]) translateElement(el, language);
  });

  const title = document.querySelector("title");
  if (title) {
    if (!originals.has(title)) originals.set(title, title.textContent);
    const original = originals.get(title);
    if (language === "ru") title.textContent = translations[original] || original;
    else title.textContent = original;
  }

  const description = document.querySelector('meta[name="description"]');
  if (description) {
    if (!originals.has(description)) originals.set(description, description.content);
    const original = originals.get(description);
    description.content = language === "ru"
      ? "Приватный Minecraft-клиент Nemesis. Базовый доступ бесплатно."
      : original;
  }

  const button = document.getElementById("languageToggle");
  if (button) button.textContent = language === "ru" ? "EN" : "RU";
}

function setLanguage(language) {
  localStorage.setItem("nemesis-language", language);
  translatePage(language);
  window.dispatchEvent(new CustomEvent("nemesis-language-change", { detail: language }));
}

window.nemesisLanguage = getLanguage;
window.nemesisSetLanguage = setLanguage;
window.nemesisTranslations = translations;

document.documentElement.classList.add("ready");
addLanguageToggle();
translatePage(getLanguage());

